import type { ActorId, Choice, Effects, StoryNode } from "../game/types";

type DraftChoice = Omit<Choice, "id">;
const sources = {
  map: "https://ncode.syosetu.com/n9669bk/72/",
  magic: "https://ncode.syosetu.com/n9669bk/4/",
  sword: "https://ncode.syosetu.com/n9669bk/6/",
  guild: "https://ncode.syosetu.com/n9669bk/29/",
  timeline: "https://ncode.syosetu.com/n9669bk/284/",
  people: "https://promo.kadokawa.co.jp/mfbooks/special/mushoku/mushoku.html",
};
function choice(
  label: string,
  detail: string,
  target: string,
  feedback: string,
  effects: Effects = {},
  extra: Partial<DraftChoice> = {},
): DraftChoice {
  return { label, detail, target, feedback, effects, risk: "safe", ...extra };
}
function node(
  id: string,
  chapter: number,
  title: string,
  location: string,
  year: StoryNode["year"],
  body: string,
  choices: DraftChoice[],
  extra: Partial<StoryNode> = {},
): StoryNode {
  return {
    id,
    chapter,
    title,
    location,
    year,
    body,
    choices: choices.map((value, index) => ({
      ...value,
      id: `${id}:${index + 1}`,
    })),
    kind: "decision",
    tag: "IF",
    source: sources.map,
    ...extra,
  };
}
const identities: ActorId[] = ["custom", "rudeus", "eris", "sylphie", "roxy"];
const identityLabels: Record<ActorId, string> = {
  custom: "回到自己的家门",
  rudeus: "回到格雷拉特家的书房",
  eris: "回到伯雷亚斯家的练习场",
  sylphie: "回到布耶纳村的树下",
  roxy: "回到米格路德村落的火塘",
};
function identityRoutes(prefix: string, suffix = ""): DraftChoice[] {
  return identities.map((actor) =>
    choice(
      identityLabels[actor],
      "继续这段人生的专属经历。",
      `${prefix}-${actor}${suffix}`,
      "你将课堂里学到的东西带回了自己的生活。",
      {},
      { actors: [actor] },
    ),
  );
}

